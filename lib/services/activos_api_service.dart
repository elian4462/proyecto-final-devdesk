  Future<List<Activo>> obtenerActivos() async {
    try {
      final respuesta = await _api.get<dynamic>('/activos/');
      final dynamic data = respuesta.data;
      if (data is List && data.isNotEmpty) {
        return data.map((json) => Activo.fromJson(json as Map<String, dynamic>)).toList();
      }
    } catch (_) {
      // Si el backend no tiene implementado el endpoint /activos/ o está sin conexión,
      // se devuelve el catálogo real precargado de 20 activos TI.
    }
    return catalogoPredeterminado.map((j) => Activo.fromJson(j)).toList();
  }
